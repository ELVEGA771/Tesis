import networkx as nx

G = nx.MultiDiGraph()

# --- Clases ---
G.add_node("Alternative", type="Class")
G.add_node("ArchitectureDecisionRecord", type="Class", comment="Identidad = repositorio + fileName; el numero declarado no es clave. El id de nodo es un slug de ambos.")
G.add_node("Decision", type="Class")
G.add_node("Document", type="Class")
G.add_node("GroundedElement", type="Class", comment="Elemento extraido del texto de un ADR. Toda instancia debe llevar evidenceSnippet con un fragmento literal de su ADR de origen; si el fragmento no aparece en el fichero, el nodo es no fundamentado.")
G.add_node("NormalizedStatus", type="Class")
G.add_node("RelationDeclaration", type="Class", pivot=True, comment="Una por cada documento que afirma la relacion. Si los dos ADR la declaran, hay dos.")
G.add_node("RelationType", type="Class", comment="Vocabulario cerrado de tipos de relacion entre ADR.")
G.add_node("Repository", type="Class")
G.add_node("StatusDeclaration", type="Class")
G.add_node("Topic", type="Class", comment="Se asigna, no se extrae: los ADR de una misma cadena de reemplazo comparten el mismo nodo Topic.")

# --- Object properties ---
G.add_node("addressesTopic", type="ObjectProperty")
G.add_node("belongsToRepository", type="ObjectProperty", characteristics=["Functional"])
G.add_node("considersAlternative", type="ObjectProperty")
G.add_node("containsADR", type="ObjectProperty")
G.add_node("declaresRelation", type="ObjectProperty", comment="Va desde el documento que contiene la afirmacion hacia la declaracion.")
G.add_node("hasNormalizedStatus", type="ObjectProperty", characteristics=["Functional"])
G.add_node("hasStatusDeclaration", type="ObjectProperty", characteristics=["Functional"])
G.add_node("recordsDecision", type="ObjectProperty", characteristics=["Functional"])
G.add_node("relationType", type="ObjectProperty", characteristics=["Functional"])
G.add_node("selectsAlternative", type="ObjectProperty", characteristics=["Functional"], comment="Si la opcion elegida no figura entre las listadas, se crea como Alternative con la frase de la eleccion como evidencia.")
G.add_node("sourceADR", type="ObjectProperty", comment="Va desde el ADR NUEVO (el que reemplaza o enmienda) hacia la declaracion.")
G.add_node("targetADR", type="ObjectProperty", comment="Va desde el ADR AFECTADO (el reemplazado o enmendado) hacia la declaracion.")

# --- Datatype properties ---
G.add_node("alternativeDescription", type="DatatypeProperty")
G.add_node("decisionDescription", type="DatatypeProperty")
G.add_node("evidenceSnippet", type="DatatypeProperty")
G.add_node("fileName", type="DatatypeProperty", characteristics=["Functional"])
G.add_node("rawStatusLiteral", type="DatatypeProperty", characteristics=["Functional"])
G.add_node("recordDate", type="DatatypeProperty", characteristics=["Functional"], comment="Se toma de los metadatos del corpus (corpus_manifest.csv / git), no la extrae el LLM.")
G.add_node("repositoryName", type="DatatypeProperty", characteristics=["Functional"])
G.add_node("title", type="DatatypeProperty", characteristics=["Functional"])
G.add_node("topicName", type="DatatypeProperty", characteristics=["Functional"])

# --- Tipos de dato ---
G.add_node("xsd:date", type="Datatype")
G.add_node("xsd:string", type="Datatype")

# --- Individuos ---
G.add_node("reltype_amends", type="RelationType", comment="El ADR origen modifica al ADR destino, que sigue vigente (amends / amended by).")
G.add_node("reltype_supersedes", type="RelationType", comment="El ADR origen deja sin vigencia al ADR destino (superseded by / supersedes / replaces).")
G.add_node("status_accepted", type="NormalizedStatus")
G.add_node("status_amended", type="NormalizedStatus")
G.add_node("status_deprecated", type="NormalizedStatus")
G.add_node("status_proposed", type="NormalizedStatus")
G.add_node("status_rejected", type="NormalizedStatus")
G.add_node("status_superseded", type="NormalizedStatus")

# --- Axiomas ---
G.add_edge("Alternative", "GroundedElement", relation="subClassOf")
G.add_edge("ArchitectureDecisionRecord", "Document", relation="subClassOf")
G.add_edge("Decision", "GroundedElement", relation="subClassOf")
G.add_edge("RelationDeclaration", "GroundedElement", relation="subClassOf")
G.add_edge("StatusDeclaration", "GroundedElement", relation="subClassOf")
G.add_edge("addressesTopic", "ArchitectureDecisionRecord", relation="domain")
G.add_edge("alternativeDescription", "Alternative", relation="domain")
G.add_edge("belongsToRepository", "ArchitectureDecisionRecord", relation="domain")
G.add_edge("considersAlternative", "ArchitectureDecisionRecord", relation="domain")
G.add_edge("containsADR", "Repository", relation="domain")
G.add_edge("decisionDescription", "Decision", relation="domain")
G.add_edge("declaresRelation", "ArchitectureDecisionRecord", relation="domain")
G.add_edge("evidenceSnippet", "GroundedElement", relation="domain")
G.add_edge("fileName", "ArchitectureDecisionRecord", relation="domain")
G.add_edge("hasNormalizedStatus", "StatusDeclaration", relation="domain")
G.add_edge("hasStatusDeclaration", "ArchitectureDecisionRecord", relation="domain")
G.add_edge("rawStatusLiteral", "StatusDeclaration", relation="domain")
G.add_edge("recordDate", "ArchitectureDecisionRecord", relation="domain")
G.add_edge("recordsDecision", "ArchitectureDecisionRecord", relation="domain")
G.add_edge("relationType", "RelationDeclaration", relation="domain")
G.add_edge("repositoryName", "Repository", relation="domain")
G.add_edge("selectsAlternative", "ArchitectureDecisionRecord", relation="domain")
G.add_edge("sourceADR", "ArchitectureDecisionRecord", relation="domain")
G.add_edge("targetADR", "ArchitectureDecisionRecord", relation="domain")
G.add_edge("title", "ArchitectureDecisionRecord", relation="domain")
G.add_edge("topicName", "Topic", relation="domain")
G.add_edge("addressesTopic", "Topic", relation="range")
